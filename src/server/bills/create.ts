import { and, eq, inArray } from "drizzle-orm";
import { cleanDisplayName, cleanFreeText } from "@/lib/names";
import { computeSplit, splitInputSchema, type SplitIssue } from "@/lib/split";
import { recordAudit } from "@/server/audit";
import { endOfManilaDay } from "@/server/billing/dates";
import { generateReference, isReferenceCollision, referenceSuffix } from "@/server/billing/reference";
import { manilaDateKey, periodOf } from "@/server/billing/period";
import type { Statement } from "@/server/billing/statements";
import type { Db } from "@/server/db/client";
import { bills, statements, users } from "@/server/db/schema";
import { notifyStatementEvent } from "@/server/email/notify";
import { ensureOneOffPlan } from "./one-off-plan";

type Bill = typeof bills.$inferSelect;

const asDb = (tx: unknown) => tx as Db;

export const MAX_TITLE_LENGTH = 80;
export const MAX_NOTE_LENGTH = 500;
const MAX_REFERENCE_ATTEMPTS = 5;
/** Generated by the browser (crypto.randomUUID), but any safe token of this shape is accepted. */
const BILL_ID = /^[A-Za-z0-9-]{8,64}$/;

export interface CreateBillInput {
  /** Chosen by the form when it opens: it is the bill's id and the rounding seed, so a preview matches what is saved. */
  billId: string;
  title: string;
  note?: string | null;
  /** The due day as "YYYY-MM-DD" (Manila). The bill is on time until that day has ended. */
  dueDate: string;
  /** The split exactly as the builder produced it; validated and recomputed here, never trusted. */
  split: unknown;
  actorId: string;
  now?: Date;
  /** Test seam for forcing reference collisions. */
  suffix?: () => string;
}

export type CreateBillResult =
  | { ok: true; created: boolean; bill: Bill; statements: Statement[] }
  | {
      ok: false;
      error:
        | "FORBIDDEN"
        | "INVALID_BILL_ID"
        | "TITLE_REQUIRED"
        | "TITLE_TOO_LONG"
        | "NOTE_TOO_LONG"
        | "INVALID_DUE_DATE"
        | "DUE_IN_PAST"
        | "BILL_CANCELLED"
        | "UNKNOWN_PARTICIPANT"
        | "NOBODY_TO_COLLECT_FROM";
    }
  | { ok: false; error: "SPLIT_INVALID"; issues: SplitIssue[] };

/** Defence in depth: the server actions already require an admin; the domain checks again. */
export function isActiveAdmin(db: Db, userId: string): boolean {
  const user = db.select({ role: users.role, isActive: users.isActive }).from(users).where(eq(users.id, userId)).get();
  return user?.role === "ADMIN" && user.isActive;
}

function billWithStatements(db: Db, billId: string): { bill: Bill; statements: Statement[] } | null {
  const bill = db.select().from(bills).where(eq(bills.id, billId)).get();
  if (!bill) return null;
  return { bill, statements: db.select().from(statements).where(eq(statements.billId, billId)).all() };
}

/**
 * Creates an ambag: stores the bill and how it was split, gives every friend their own statement (the admin who
 * fronted the money gets none for their own share), and queues each friend's "your ambag is ready" email.
 * One immediate transaction. Submitting the same bill id again returns the existing bill and changes nothing.
 */
export function createBill(db: Db, input: CreateBillInput): CreateBillResult {
  const now = input.now ?? new Date();

  if (!isActiveAdmin(db, input.actorId)) return { ok: false, error: "FORBIDDEN" };
  if (!BILL_ID.test(input.billId)) return { ok: false, error: "INVALID_BILL_ID" };

  // A double click or a retry after a slow response: hand back what was already made.
  const already = billWithStatements(db, input.billId);
  if (already) return already.bill.cancelledAt ? { ok: false, error: "BILL_CANCELLED" } : { ok: true, created: false, ...already };

  const title = cleanDisplayName(input.title);
  if (title.length === 0) return { ok: false, error: "TITLE_REQUIRED" };
  if (title.length > MAX_TITLE_LENGTH) return { ok: false, error: "TITLE_TOO_LONG" };
  const note = (input.note ? cleanFreeText(input.note) : "") || null;
  if (note && note.length > MAX_NOTE_LENGTH) return { ok: false, error: "NOTE_TOO_LONG" };
  const dueAt = endOfManilaDay(input.dueDate);
  if (!dueAt) return { ok: false, error: "INVALID_DUE_DATE" };
  if (input.dueDate < manilaDateKey(now)) return { ok: false, error: "DUE_IN_PAST" };

  const outcome = computeSplit(input.split, input.billId);
  if (!outcome.ok) return { ok: false, error: "SPLIT_INVALID", issues: outcome.issues };
  const { result } = outcome;
  const splitInput = splitInputSchema.parse(input.split);

  const participantIds = result.shares.map((share) => share.userId);
  const everyoneIsActive = (d: Db) =>
    d
      .select({ id: users.id })
      .from(users)
      .where(and(inArray(users.id, participantIds), eq(users.isActive, true)))
      .all().length === participantIds.length;
  if (!everyoneIsActive(db)) return { ok: false, error: "UNKNOWN_PARTICIPANT" };

  // The admin who fronted the money has no statement for their own share, and nobody is billed for nothing.
  const collecting = result.shares.filter((share) => share.userId !== input.actorId && share.amountMinor > 0);
  if (collecting.length === 0) return { ok: false, error: "NOBODY_TO_COLLECT_FROM" };

  return db.transaction((tx): CreateBillResult => {
    const t = asDb(tx);
    const raced = billWithStatements(t, input.billId);
    if (raced) return raced.bill.cancelledAt ? { ok: false, error: "BILL_CANCELLED" } : { ok: true, created: false, ...raced };
    // Checked again under the write lock: an admin demoted or a friend deactivated a moment ago must not slip through.
    if (!isActiveAdmin(t, input.actorId)) return { ok: false, error: "FORBIDDEN" };
    if (!everyoneIsActive(t)) return { ok: false, error: "UNKNOWN_PARTICIPANT" };

    const plan = ensureOneOffPlan(t);
    const period = periodOf(now);
    const bill = t
      .insert(bills)
      .values({
        id: input.billId,
        title,
        note,
        totalMinor: result.totalMinor,
        currency: plan.currency,
        splitMethod: result.method,
        splitInput,
        splitResult: result,
        engineVersion: result.engine,
        dueAt,
        createdBy: input.actorId,
        createdAt: now,
      })
      .returning()
      .get();

    const issued: Statement[] = [];
    for (const share of collecting) {
      issued.push(insertShareStatement(t, { plan, period, bill, userId: share.userId, amountMinor: share.amountMinor, now, suffix: input.suffix ?? referenceSuffix }));
    }

    recordAudit(t, {
      actorId: input.actorId,
      action: "bill.created",
      entityType: "bill",
      entityId: bill.id,
      metadata: { title, totalMinor: bill.totalMinor, method: bill.splitMethod, participants: result.shares.length, collectingFrom: issued.length },
    });

    // The same dedupe key the daily job uses, so it never sends a second "ready" email for these.
    for (const statement of issued) {
      notifyStatementEvent(t, { type: "SOA_GENERATED", statement, dedupeKey: `SOA_GENERATED:${statement.id}`, now });
    }

    return { ok: true, created: true, bill, statements: issued };
  }, { behavior: "immediate" });
}

function insertShareStatement(
  t: Db,
  args: { plan: { id: string; refPrefix: string }; period: string; bill: Bill; userId: string; amountMinor: number; now: Date; suffix: () => string },
): Statement {
  for (let attempt = 0; attempt < MAX_REFERENCE_ATTEMPTS; attempt++) {
    try {
      return t
        .insert(statements)
        .values({
          reference: generateReference(args.plan.refPrefix, args.period, args.suffix),
          userId: args.userId,
          subscriptionId: args.plan.id,
          period: args.period,
          // Snapshot of the title, like a plan's name on a monthly statement.
          subscriptionName: args.bill.title,
          amountMinor: args.amountMinor,
          outstandingMinor: args.amountMinor,
          currency: args.bill.currency,
          issuedAt: args.now,
          dueAt: args.bill.dueAt,
          billId: args.bill.id,
        })
        .returning()
        .get();
    } catch (error) {
      // A random reference collided with an existing one: draw again. Anything else is a real failure.
      if (!isReferenceCollision(error)) throw error;
    }
  }
  throw new Error("Could not generate a unique statement reference");
}
